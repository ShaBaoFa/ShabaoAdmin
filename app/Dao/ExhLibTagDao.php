namespace App\Dao;

use App\Base\BaseDao;
use App\Model\ExhLibTag;
use Hyperf\Collection\Arr;
use Hyperf\Database\Model\Builder;

class ExhLibTagDao extends BaseDao
{
    /**
     * @var ExhLibTag
     */
    public $model;

    public function assignModel(): void
    {
        $this->model = ExhLibTag::class;
    }

    /**
     * 搜索处理器.
     */
    public function handleSearch(Builder $query, array $params): Builder
    {
        $query->when(
            Arr::get($params, 'name'),
            fn (Builder $query, $name) => $query->where('name', 'like', '%' . $name . '%')
        );


        $query->when(
            Arr::get($params, 'created_at'),
            function (Builder $query, $createdAt) {
                if (is_array($createdAt) && count($createdAt) === 2) {
                    $query->whereBetween(
                        'created_at',
                        [$createdAt[0] . ' 00:00:00', $createdAt[1] . ' 23:59:59']
                    );
                }
            }
        );

        return $query;
    }
}
